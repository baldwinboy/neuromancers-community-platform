"""Auth adapters for the vendored GetPronto and Whereby API clients.

The vendored clients are generated by ``clientele`` and build their HTTP client
at import time, reading ``Config().headers`` on every request. The API keys are
managed by Wagtail admins via ``IntegrationSettings`` (core.models), so this
module injects them into the live clients' config right before a call is made.
"""

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from clientele.api import APIClient


def _configure_client(client: APIClient, header: str | None) -> None:
    """Replace the Authorization header on a vendored clientele client."""
    headers = client.config.headers
    if header:
        headers["Authorization"] = header
    else:
        headers.pop("Authorization", None)


def configure_getpronto() -> None:
    """Authenticate the vendored GetPronto client with the configured API key."""
    from getpronto.client import client  # noqa: PLC0415
    from neuromancers_network.core.models import IntegrationSettings  # noqa: PLC0415

    key = IntegrationSettings.load().getpronto_api_key
    _configure_client(client, f"ApiKey {key}" if key else None)


def configure_whereby() -> None:
    """Authenticate the vendored Whereby client with the configured API key."""
    from neuromancers_network.core.models import IntegrationSettings  # noqa: PLC0415
    from whereby.client import client  # noqa: PLC0415

    key = IntegrationSettings.load().whereby_api_key
    _configure_client(client, f"Bearer {key}" if key else None)


def whereby_room_prefix() -> str | None:
    """Return the configured Whereby room-name prefix, if any."""
    from neuromancers_network.core.models import IntegrationSettings  # noqa: PLC0415

    prefix = IntegrationSettings.load().whereby_room_prefix
    return prefix or None
